const strip = (s: string) =>
  s
    .replace(/\(.*?\)/g, "")
    .replace(/^\s*محافظة\s+/, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .trim();

/** Finds a governorate by its stored name ("محافظة الغربية (وسط الدلتا)" and "الغربية" both match). */
export function findEgyptGovernorate(name?: string): EgyptGovernorate | undefined {
  if (!name) return undefined;
  const k = strip(name);
  return egyptGovernorates.find((e) => strip(e.name) === k);
}

export const citiesOf = (govName?: string): string[] => findEgyptGovernorate(govName)?.cities ?? [];
